function interpolate(str, vars) {
  if (!str) return '';
  return str.replace(/\{(\w+)\}/g, (m, k) => (vars && vars[k] !== undefined ? vars[k] : m));
}

function makeT(lang) {
  const dict = LOCALES[lang] || LOCALES.en;
  return (key, vars) => interpolate(dict[key] !== undefined ? dict[key] : LOCALES.en[key] !== undefined ? LOCALES.en[key] : key, vars);
}
